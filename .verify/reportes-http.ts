process.env.DATABASE_URL = 'postgres://postgres@127.0.0.1:55432/sgh';
process.env.DATABASE_SSL = 'false';
import express, { Router } from 'express';
const { getDatabasePool } = await import('../server/config/database.ts');
const { errorHandler } = await import('../server/middleware/error-handler.ts');
const { registerM4Gestion } = await import('../server/modules/gestion/m4.ts');
const { registerM3Gestion } = await import('../server/modules/gestion/m3.ts');
const pool = getDatabasePool();
const one = async (sql: string, p: any[] = []) => (await pool.query(sql, p)).rows[0];

const admin: any = { authUserId: '00000000-0000-0000-0000-000000000001', usuarioId: '1', codigoUsuario: 'verif', nombre: 'V', departamento: 'TI', roles: ['ADMINISTRADOR'], permisos: ['*'], canViewFullPII: true, idUsuarioG4: 1, idPersonalG2: '1' };
const sinPermiso: any = { ...admin, roles: ['CAJERO'], permisos: ['m4.caja.operar'] };
let ctx: any = admin;
const app = express();
app.use(express.json());
const r = Router();
r.use((req, _res, next) => { (req as any).authContext = ctx; next(); });
registerM4Gestion(r);
registerM3Gestion(r);
app.use('/m4', r);
app.use(errorHandler);
const server = await new Promise<any>((res) => { const s = app.listen(0, '127.0.0.1', () => res(s)); });
const base = `http://127.0.0.1:${server.address().port}`;
const call = async (path: string) => { const x = await fetch(base + path, { headers: { 'X-Requested-With': 'SGH-ERP' } }); return { status: x.status, json: await x.json().catch(() => null) }; };

let ok = 0, bad = 0;
const check = (name: string, cond: boolean, extra = '') => { if (cond) { console.log(`OK   ${name}`); ok++; } else { console.log(`FAIL ${name} ${extra}`); bad++; } };
const near = (a: number, b: number) => Math.abs(a - b) < 0.01;

let res = await call('/m4/reportes/resumen?desde=2026-01-01&hasta=2026-12-31');
check('GET resumen => 200', res.status === 200, JSON.stringify(res).slice(0, 200));
const d = res.json.data;
const fact = await one(`select coalesce(sum(total),0)::float n from g4_finanzas.comprobante where estado in ('ACEPTADO','ENVIADO','FIRMADO') and fecha_emision::date between '2026-01-01' and '2026-12-31'`);
check('  facturado = suma de comprobantes aceptados/enviados/firmados', near(d.totales.facturado, fact.n), `${d.totales.facturado} vs ${fact.n}`);
const cob = await one(`select coalesce(sum(monto),0)::float n from g4_finanzas.cobro where estado='REGISTRADO' and fecha_hora::date between '2026-01-01' and '2026-12-31'`);
check('  cobrado = suma de cobros registrados', near(d.totales.cobrado, cob.n));
const gas = await one(`select coalesce(sum(monto),0)::float n from g4_finanzas.gasto where estado='APROBADO' and fecha between '2026-01-01' and '2026-12-31'`);
check('  gastos = suma de gastos aprobados', near(d.totales.gastos, gas.n));
check('  5 semanas y 6 meses', d.semanal.length === 5 && d.mensual.length === 6);
const semTot = d.semanal.reduce((a: number, x: any) => a + x.ingresos, 0);
const sem = await one(`select coalesce(sum(total),0)::float n from g4_finanzas.comprobante where estado in ('ACEPTADO','ENVIADO','FIRMADO') and fecha_emision::date between current_date-34 and current_date`);
check('  semanas suman lo emitido en los últimos 35 días', near(semTot, sem.n), `${semTot} vs ${sem.n}`);
check('  semanas contiguas y la última termina hoy', d.semanal[4].hasta === (await one(`select current_date::text d`)).d && d.semanal.every((x: any, i: number) => i === 0 || x.desde > d.semanal[i - 1].hasta));
const ult = d.mensual[5];
const mes = await one(`select coalesce(sum(total),0)::float n from g4_finanzas.comprobante where estado in ('ACEPTADO','ENVIADO','FIRMADO') and date_trunc('month', fecha_emision) = date_trunc('month', current_date)`);
check('  mes actual coincide', near(ult.ingresos, mes.n) && ult.mes === (await one(`select to_char(current_date,'YYYY-MM') m`)).m);
const areasIng = d.areas.reduce((a: number, x: any) => a + x.ingresos, 0);
const ci = await one(`select coalesce(sum(importe),0)::float n from g4_finanzas.consumo where fecha between '2026-01-01' and '2026-12-31'`);
check('  áreas: ingresos = consumos del rango', near(areasIng, ci.n));
check('  áreas: costos = gastos aprobados', near(d.areas.reduce((a: number, x: any) => a + x.costos, 0), gas.n));
res = await call('/m4/reportes/resumen');
check('  sin fechas: últimos 30 días', res.status === 200 && res.json.data.hasta === (await one(`select current_date::text d`)).d);
res = await call('/m4/reportes/resumen?desde=2026-05-01&hasta=2026-01-01');
check('  rango invertido => 4xx', res.status >= 400 && res.status < 500, JSON.stringify(res));
res = await call('/m4/reportes/resumen?desde=basura');
check('  fecha inválida => 4xx', res.status >= 400 && res.status < 500, JSON.stringify(res));
ctx = sinPermiso;
res = await call('/m4/reportes/resumen');
check('  sin permiso => 403', res.status === 403);

console.log(`\n${ok} OK · ${bad} FAIL`);
server.close();
await pool.end();
process.exit(bad ? 1 : 0);
